#!/usr/bin/env python3
"""Generate the Go release-channel constants from the root configuration."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "release-channel.json"
TARGET = ROOT / "backend/internal/releasechannel/channel_gen.go"
INSTALLER = ROOT / "deploy/install.sh"
REPOSITORY_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
VERSION_RE = re.compile(r"^v\d+\.\d+\.\d+\+custom\.\d{3}$")
RUNTIME_PATH_RE = re.compile(r"^[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*$")


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def load_config() -> dict[str, object]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    required_keys = {
        "release_repository",
        "release_image",
        "upstream_repository",
        "upstream_baseline",
        "runtime_files",
    }
    if set(data) != required_keys:
        raise ValueError(
            "release-channel.json keys must be exactly: "
            + ", ".join(sorted(required_keys))
        )

    for key in ("release_repository", "upstream_repository"):
        value = data[key]
        if not isinstance(value, str) or REPOSITORY_RE.fullmatch(value) is None:
            raise ValueError(f"{key} must be an owner/repository name")

    image = data["release_image"]
    if not isinstance(image, str) or not image.startswith("ghcr.io/"):
        raise ValueError("release_image must be a ghcr.io image name")

    baseline = data["upstream_baseline"]
    if not isinstance(baseline, str) or VERSION_RE.fullmatch(baseline) is None:
        raise ValueError("upstream_baseline must use vX.Y.Z+custom.NNN")

    runtime_files = data["runtime_files"]
    if not isinstance(runtime_files, list) or not runtime_files:
        raise ValueError("runtime_files must be a non-empty list")
    seen: set[str] = set()
    for item in runtime_files:
        if not isinstance(item, dict) or set(item) != {"path", "required"}:
            raise ValueError("each runtime file needs only path and required")
        path = item["path"]
        required = item["required"]
        if not isinstance(path, str) or RUNTIME_PATH_RE.fullmatch(path) is None:
            raise ValueError(f"invalid runtime file path: {path!r}")
        if path in seen:
            raise ValueError(f"duplicate runtime file path: {path}")
        if not isinstance(required, bool):
            raise ValueError(f"runtime file required flag must be boolean: {path}")
        seen.add(path)

    if "release-channel.json" not in seen:
        raise ValueError("runtime_files must include release-channel.json")
    goreleaser = (ROOT / ".goreleaser.yaml").read_text(encoding="utf-8")
    for path in seen:
        source = path if path == "release-channel.json" else f"backend/{path}"
        if f"- src: {source}" not in goreleaser:
            raise ValueError(f".goreleaser.yaml does not package runtime file: {source}")
    return data


def render(data: dict[str, object]) -> str:
    runtime_rows = "\n".join(
        "\t{Path: %s, Required: %s},"
        % (quoted(item["path"]), str(item["required"]).lower())
        for item in data["runtime_files"]  # type: ignore[union-attr]
    )
    return f'''// Code generated by tools/generate_release_channel.py; DO NOT EDIT.

package releasechannel

const (
\tReleaseRepository  = {quoted(data["release_repository"])}
\tReleaseImage       = {quoted(data["release_image"])}
\tUpstreamRepository = {quoted(data["upstream_repository"])}
\tUpstreamBaseline   = {quoted(data["upstream_baseline"])}
)

type RuntimeFile struct {{
\tPath     string
\tRequired bool
}}

var RuntimeFiles = []RuntimeFile{{
{runtime_rows}
}}
'''


def installer_block(data: dict[str, object]) -> str:
    return (
        "# BEGIN GENERATED RELEASE CHANNEL\n"
        f'GITHUB_REPO={quoted(data["release_repository"])}\n'
        "# END GENERATED RELEASE CHANNEL"
    )


def render_installer(data: dict[str, object]) -> str:
    text = INSTALLER.read_text(encoding="utf-8")
    updated, replacements = re.subn(
        r"# BEGIN GENERATED RELEASE CHANNEL\n.*?\n# END GENERATED RELEASE CHANNEL",
        installer_block(data),
        text,
        flags=re.DOTALL,
    )
    if replacements != 1:
        raise ValueError("deploy/install.sh must contain one generated release-channel block")
    return updated


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    data = load_config()
    generated = render(data)
    installer = render_installer(data)
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != generated:
            raise SystemExit(
                "generated release channel is stale; run: "
                "python3 tools/generate_release_channel.py"
            )
        if INSTALLER.read_text(encoding="utf-8") != installer:
            raise SystemExit(
                "generated installer release channel is stale; run: "
                "python3 tools/generate_release_channel.py"
            )
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated, encoding="utf-8")
    INSTALLER.write_text(installer, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
