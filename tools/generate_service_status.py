#!/usr/bin/env python3
"""Generate the passive service status rules from the root parameter file."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
config = json.loads((root / 'service-status.json').read_text())
output = '// Code generated by tools/generate_service_status.py; DO NOT EDIT.\npackage service\n\n'
output += 'var serviceStatusConfig = ServiceStatusConfig{\n'
output += f'\tRecentRequests:      {config["recent_requests"]},\n'
output += f'\tNormalSuccessRate:   {json.dumps(config["normal_success_rate"])},\n'
output += f'\tDegradedSuccessRate: {json.dumps(config["degraded_success_rate"])},\n'
output += f'\tBucketCount:         {config["bucket_count"]},\n'
output += f'\tBucketMinutes:       {config["bucket_minutes"]},\n'
output += f'\tCacheSeconds:        {config["cache_seconds"]},\n'
output += '}\n'
(root / 'backend/internal/service/service_status_config_gotocc.go').write_text(output)
