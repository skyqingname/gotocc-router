#!/usr/bin/env python3
"""Generate the daily check-in rules from the root parameter file."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
config = json.loads((root / 'daily-checkin.json').read_text())
milestones = ''.join(
    f'\t\t{{Days: {item["days"]}, Reward: {json.dumps(item["reward"])}}},\n' for item in config['milestones'])
strings = lambda values: ', '.join(json.dumps(value) for value in values)
output = '// Code generated by tools/generate_daily_checkin.py; DO NOT EDIT.\npackage service\n\n'
output += 'var dailyCheckinConfig = DailyCheckinConfig{\n'
output += f'\tDailyReward: {json.dumps(config["daily_reward"])},\n'
output += '\tMilestones: []DailyCheckinMilestone{\n' + milestones + '\t},\n'
output += f'\tUnlockRedeemTypes:     []string{{{strings(config["unlock"]["redeem_code_types"])}}},\n'
output += f'\tUnlockPaymentStatuses: []string{{{strings(config["unlock"]["payment_order_statuses"])}}},\n'
output += '}\n'
(root / 'backend/internal/service/daily_checkin_config_gotocc.go').write_text(output)
