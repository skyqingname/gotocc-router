#!/usr/bin/env python3
"""Generate affiliate defaults from the root parameter file."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
cfg = json.loads((root / 'affiliate-defaults.json').read_text())
rates = cfg['rebate_rates_percent']
output = '// Code generated by tools/generate_affiliate_defaults.py; DO NOT EDIT.\npackage service\n\n'
output += f'const AffiliateRebateGenerations = {len(rates)}\n'
for name, value in zip(['AffiliateRebateRateDefault', 'AffiliateRebateRateL2Default', 'AffiliateRebateRateL3Default'], rates):
    output += f'const {name} = {float(value)}\n'
# Sentinel written at migration time; the first boot after the upgrade replaces it
# with the real enrollment cutoff exactly once. "1970-01-01" means "not yet set".
output += f'\n// AgentEnrollmentCutoffSentinel marks an enrollment cutoff that is not yet effective.\nconst AgentEnrollmentCutoffSentinel = "{cfg["agent_enrollment_cutoff_sentinel"]}"\n'
(root / 'backend/internal/service/affiliate_defaults_gen.go').write_text(output)
