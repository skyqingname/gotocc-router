#!/usr/bin/env python3
"""Generate balance cashback defaults from the root parameter file."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
config = json.loads((root / 'balance-cashback.json').read_text())
defaults = json.dumps(config['defaults'], separators=(',', ':'))
output = '// Code generated by tools/generate_balance_cashback.py; DO NOT EDIT.\npackage service\n\n'
output += f'const balanceCashbackDefaultsJSON = `{defaults}`\n'
output += f'const balanceCashbackDecimalPlaces = {config["amount_decimal_places"]}\n'
(root / 'backend/internal/service/balance_cashback_defaults_gotocc.go').write_text(output)
