import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
cfg = json.loads((root / 'reseller-defaults.json').read_text())
(root / 'backend/internal/pkg/reseller/defaults_gen.go').write_text('// Code generated by tools/generate_reseller_defaults.py; DO NOT EDIT.\npackage reseller\n\nconst DefaultMultiplier = ' + repr(cfg['default_multiplier']) + '\nconst MinimumMultiplier = ' + repr(cfg['minimum_multiplier']) + '\nconst PageSize = ' + repr(cfg['page_size']) + '\nconst DefaultInitialCredit = ' + repr(cfg['default_initial_credit']) + '\n')

communications = cfg['communications']
with (root / 'backend/internal/pkg/reseller/defaults_gen.go').open('a') as output:
    output.write('const DefaultContactEnabled = ' + str(communications['contact_enabled']).lower() + '\n')
    output.write('const DefaultAnnouncementsEnabled = ' + str(communications['announcements_enabled']).lower() + '\n')
    output.write('const DefaultSyncMainAnnouncements = ' + str(communications['sync_main_announcements']).lower() + '\n')
    output.write('const AnnouncementListLimit = ' + str(communications['announcement_list_limit']) + '\n')
    output.write('const AnnouncementTitleMaxLength = ' + str(communications['announcement_title_max_length']) + '\n')
