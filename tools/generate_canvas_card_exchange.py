#!/usr/bin/env python3
"""Generate canvas card exchange parameters from the product root JSON."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
config = json.loads((root / 'canvas-card-exchange.json').read_text())
output = '// Code generated by tools/generate_canvas_card_exchange.py; DO NOT EDIT.\npackage service\n\n'
output += 'var canvasCardDenominations = []int{' + ', '.join(map(str, config['denominations'])) + '}\n'
output += f'const CanvasCardPageSize = {config["page_size"]}\n'
output += f'const canvasCardImportLimit = {config["import_batch_limit"]}\n'
(root / 'backend/internal/service/canvas_card_defaults_gotocc.go').write_text(output)
