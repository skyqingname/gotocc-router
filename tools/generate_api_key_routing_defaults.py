#!/usr/bin/env python3
"""Generate the initial smart-routing policy from its root parameter file."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
config = json.loads((root / 'api-key-routing-defaults.json').read_text())


def group_ids(values):
    return '[]int64{' + ', '.join(str(value) for value in values) + '}'


rules = ',\n'.join(
    '\t\t\t{Model: ' + json.dumps(rule['model'], ensure_ascii=False)
    + ', GroupIDs: ' + group_ids(rule['group_ids']) + '}'
    for rule in config['model_rules']
)
if rules:
    rules += ',\n'
output = '''// Code generated by tools/generate_api_key_routing_defaults.py; DO NOT EDIT.
package service

func defaultAutoGroupRoutingPolicy() *AutoGroupRoutingPolicy {
\treturn &AutoGroupRoutingPolicy{
\t\tAllowUserOverride: ''' + str(config['allow_user_override']).lower() + ''',
\t\tDefaultGroupOrder: ''' + group_ids(config['default_group_order']) + ''',
\t\tModelRules: []AutoGroupRoutingRule{
''' + rules + '''\t\t},
\t}
}
'''
(root / 'backend/internal/service/api_key_routing_defaults_gotocc.go').write_text(output)
